def translate(key: str, lang: str = "en", **kwargs) -> str:
    """
    Translates a given translation key for the specified language.
    Falls back to English if the key is not in target language.
    Falls back to a readable key format if not in English.
    """
    if lang not in TRANSLATIONS:
        lang = "en"
    
    text = TRANSLATIONS.get(lang, {}).get(key)
    if text is None and lang != "en":
        text = TRANSLATIONS.get("en", {}).get(key)
    
    if text is None:
        text = key.replace("_", " ").title()
        
    if kwargs:
        try:
            return Markup(text.format(**kwargs))
        except Exception:
            return Markup(text)
            
    return Markup(text)


def get_request_lang(request) -> str:
    """Extracts preferred language from cookie or query param."""
    if not request:
        return "en"
    lang = request.query_params.get("lang") or request.cookies.get("lang", "en")
    return "bn" if lang == "bn" else "en"
